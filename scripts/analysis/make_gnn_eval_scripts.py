#!/usr/bin/env python3
"""Generate eval-only SLURM scripts for GNN cells that already have weights.

Every GNN result predating the gift_eval fix was scored on stride windows, so
it has to be regenerated -- but the weights are fine, so this is an evaluation
pass, not retraining. BaseEngine.evaluate('test') loads final_model_s{seed}.pt.

The command is derived from the matching training script rather than written
by hand: model construction args differ per model (--input_dim for DSTAGNN,
--spatial_attn_chunk_size for STTN, --gconv_chunk_size for D2STGNN, ...) and a
mismatch means the checkpoint will not load. Only --mode changes.

Training scripts are never modified; these land in a separate tree and can be
deleted once the numbers are in.

    python scripts/analysis/make_gnn_eval_scripts.py            # write scripts
    python scripts/analysis/make_gnn_eval_scripts.py --dry-run  # list only
"""
import argparse
import glob
import os
import re

REPO = "/u/tliao2/TrafficFM"
TRAIN_ROOT = os.path.join(REPO, "scripts/run/gnn")
EVAL_ROOT = os.path.join(REPO, "scripts/run/gnn_eval")
EXP_ROOT = os.path.join(REPO, "benchmark/gnn/experiments")

# Evaluation is one forward pass over 20 windows; D2STGNN/SD took 30s. Give CA
# room and keep the rest short so they queue quickly.
TIME_FOR = {"sd": "00:30:00", "gba": "01:00:00", "gla": "01:30:00", "ca": "03:00:00"}

# --cpu targets the cpu partition instead. Evaluation needs no GPU, and the
# GPU queues sit ~2600 jobs deep against ~460 on cpu. Measured on CA/2018, the
# largest region: STGCN 33s/10.9G, DCRNN 85s/10.5G, GWNET 187s/17.4G,
# AGCRN 222s/12.6G, DSTAGNN 516s/20.6G, STTN 705s/14.0G. Delta charges
# max(cores, mem_GB/2), so memory sets the price on CA either way.
CPU_TIME_FOR = {"sd": "00:20:00", "gba": "00:30:00", "gla": "00:45:00", "ca": "01:30:00"}
CPU_MEM_FOR = {"sd": "4G", "gba": "8G", "gla": "12G", "ca": "32G"}
CPU_CORES_FOR = {"sd": 4, "gba": 4, "gla": 6, "ca": 8}


def has_weights(model, region, year):
    pat = os.path.join(EXP_ROOT, model.upper(), f"{region.upper()}*", year,
                       "final_model_s*.pt")
    return bool(glob.glob(pat))


def build(train_path, model, region, year, cpu=False):
    src = open(train_path).read()

    # The uv-run command is the last block; everything above it is the
    # segmented-training scaffolding, which an eval pass does not need.
    m = re.search(r"^(uv run .*?)(?=\nEXIT_CODE=)", src, re.S | re.M)
    if not m:
        return None
    cmd = m.group(1)
    cmd, n = re.subn(r"--mode\s+train", "--mode test", cmd)
    if n != 1:
        return None
    if cpu:
        cmd = re.sub(r"--device\s+\S+", "--device cpu", cmd)

    mem = re.search(r"#SBATCH --mem=(\S+)", src)
    part = re.search(r"#SBATCH --partition=(\S+)", src)
    acct = re.search(r"#SBATCH --account=(\S+)", src)
    log = f"{REPO}/log/gnn_eval/{model}/{region}/{year}"

    if cpu:
        resources = f"""#SBATCH --time={CPU_TIME_FOR[region]}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={CPU_CORES_FOR[region]}
#SBATCH --mem={CPU_MEM_FOR[region]}
#SBATCH --account=bcqc-delta-cpu
#SBATCH --partition=cpu"""
        threads = f"""
# Confine BLAS/OpenMP to the allocated cores; the libraries otherwise size
# their pools from the node's 128.
export OMP_NUM_THREADS=${{SLURM_CPUS_PER_TASK:-1}}
export OPENBLAS_NUM_THREADS=$OMP_NUM_THREADS
export MKL_NUM_THREADS=$OMP_NUM_THREADS
"""
    else:
        resources = f"""#SBATCH --time={TIME_FOR[region]}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node=1
#SBATCH --mem={mem.group(1) if mem else '32G'}
#SBATCH --account={acct.group(1) if acct else 'bcqc-delta-gpu'}
#SBATCH --partition={part.group(1) if part else 'gpuA100x4'}"""
        threads = ""

    return f"""#!/bin/bash
{resources}
#SBATCH --job-name={model}_{region}{year}_ev
#SBATCH --output={log}/%j.out
#SBATCH --error={log}/%j.err

# Evaluation only -- generated by scripts/analysis/make_gnn_eval_scripts.py
# from run_{model}_{region}_{year}.sh, with --mode train -> --mode test.
# No training, no checkpoint writes, no auto-resume chain: evaluate('test')
# loads final_model_s2023.pt and reports per-horizon metrics.
#
# Regenerate the script rather than editing it, so the model construction args
# stay in step with the training script they came from.
cd {REPO}/benchmark/gnn
{threads}
{cmd}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--cpu", action="store_true",
                    help="target the cpu partition (evaluation needs no GPU)")
    args = ap.parse_args()

    written = skipped = noweights = 0
    for train_path in sorted(glob.glob(os.path.join(TRAIN_ROOT, "*", "run_*.sh"))):
        base = os.path.basename(train_path)[len("run_"):-len(".sh")]
        parts = base.rsplit("_", 2)
        if len(parts) != 3:
            continue
        model, region, year = parts
        if region not in TIME_FOR:
            continue
        if not has_weights(model, region, year):
            noweights += 1
            continue
        body = build(train_path, model, region, year, cpu=args.cpu)
        if body is None:
            print(f"  SKIP (could not parse): {train_path}")
            skipped += 1
            continue
        # Keep the run_{slug}_{region}_{year}.sh shape that
# scripts/lib/log_layout.sh parses; the gnn_eval/ family directory
# is what separates these from the training scripts.
        out = os.path.join(EVAL_ROOT, model, f"run_{model}_{region}_{year}.sh")
        print(f"  {'would write' if args.dry_run else 'write'} {os.path.relpath(out, REPO)}")
        if not args.dry_run:
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with open(out, "w") as f:
                f.write(body)
            os.chmod(out, 0o755)
        written += 1

    print(f"\n{written} eval scripts, {skipped} unparsed, "
          f"{noweights} cells without weights (need training, not evaluation).")
    if not args.dry_run and written:
        print("Next: bash scripts/maintenance/sync_log_dirs.sh")


if __name__ == "__main__":
    main()
